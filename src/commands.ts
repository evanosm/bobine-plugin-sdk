/**
 * A group of commands applied atomically (all or nothing) as ONE undo step.
 * Times are in flicks (1 second = 705600000). Clip, track, marker and sequence-settings
 * commands target the ACTIVE sequence (`SetActiveSequence` changes it).
 */
export type Transaction = {
  commands: Command[];
  /**
   * Short human-readable description shown in the history, e.g. "Remove silences".
   */
  label: string;
  origin: Origin;
};

/**
 * Place a media on a track. If the media has audio, linked audio clips are created with ids
 * `<id>.a1`, `<id>.a2`… on the first audio tracks that are free over that range (with
 * `overwrite`: the first unlocked audio tracks). Clips split by `insert` or `overwrite` get
 * ids starting with `<id>.`.
 */
export type AddClip = {
  /**
   * Timeline position (snapped to the nearest sequence frame).
   */
  at: Flicks;
  /**
   * Default: rest of the media from `source_in` (5 s for a still image).
   */
  duration?: Flicks | null;
  /**
   * New clip id, generated by the caller.
   */
  id: ClipId;
  media: MediaId;
  /**
   * Default `free`: fails if the range is not free.
   */
  mode?: EditMode | null;
  /**
   * Start point inside the media. Default 0.
   */
  source_in?: Flicks | null;
  /**
   * Video track for a video or image media, audio track for an audio-only media.
   */
  track: TrackId;
};

export type AddMarker = {
  /**
   * The id is generated by the caller.
   */
  marker: Marker;
};

/**
 * Add a text clip (title, lower third) on a video track.
 * The text is centered on `position` (default: center of the frame). Animate its entrance
 * with keyframes: on `opacity`, `scale`, `position`, or on `text_reveal` (0 → 1) for a
 * typewriter / word cascade (`style.reveal_unit`, `style.reveal_effect`).
 * Example, a title at the top for 3 s:
 * `{id: "<new id>", track: "v2", at: 0, duration: 2116800000, text: "Day 1",
 *  style: {font_family: "Anton", font_size: 140, uppercase: true}, position: {x: 0, y: -600}}`.
 */
export type AddTextClip = {
  /**
   * Timeline position (snapped to the nearest frame).
   */
  at: Flicks;
  /**
   * Default: the project still image duration (5 s).
   */
  duration?: Flicks | null;
  /**
   * New clip id, generated by the caller.
   */
  id: ClipId;
  /**
   * Default `free`: fails if the range is not free.
   */
  mode?: EditMode | null;
  /**
   * Offset of the text center from the frame center, in sequence pixels.
   */
  position?: Vec2 | null;
  /**
   * Style changes from the default (white Montserrat 800, 96 px, centered).
   */
  style?: TextStylePatch | null;
  text: string;
  /**
   * A video track.
   */
  track: TrackId;
};

export type AddTrack = {
  /**
   * New track id, generated by the caller.
   */
  id: TrackId;
  /**
   * Display position. Default: after the last track of the same kind.
   */
  index?: number | null;
  kind: TrackKind;
  /**
   * Default: "V<n>" or "A<n>".
   */
  name?: string | null;
};

/**
 * Put a transition on the cut at the END of `clip` (between `clip` and the clip that starts
 * exactly where it ends, on the same track). It is centered on the cut and uses media
 * beyond both clip edges: without enough media the command fails with
 * `not_enough_material`, which gives the longest possible duration. A transition already on
 * that cut is replaced. On a video track, linked audio clips meeting at the same cut get a
 * constant-power audio crossfade too (ids `<id>.a1`, `<id>.a2`...).
 * Example, a 1 s cross dissolve after clip c1:
 * `{id: "<new id>", clip: "c1", kind: "crossfade", duration: 705600000}`.
 */
export type AddTransition = {
  /**
   * The clip on the LEFT of the cut.
   */
  clip: ClipId;
  /**
   * Push, slide, wipe. Default `left`.
   */
  direction?: TransitionDirection | null;
  /**
   * Default 0.5 s (snapped to frames).
   */
  duration?: Flicks | null;
  /**
   * Default `ease_in_out`.
   */
  easing?: Easing | null;
  /**
   * New transition id, generated by the caller.
   */
  id: TransitionId;
  kind: TransitionKind;
  /**
   * Default true: also crossfade the linked audio at the same cut.
   */
  with_audio?: boolean | null;
};

