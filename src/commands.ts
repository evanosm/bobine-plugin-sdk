export type ClipId = string;

export type ClipProps = {
  /**
   * Voice cleaning (see `SetCleanVoice`): noise reduction made for speech, from 0 (off) to
   * 1 (strongest). Audio clips only.
   */
  clean_voice?: number;
  /**
   * Crop and rounded corners (V4), as fractions of the image.
   */
  crop?: Crop;
  /**
   * Fade at the start of the clip (V4), multiplied with the opacity (video) or the volume
   * (audio) keyframes. `fade_in + fade_out` never exceeds the clip duration.
   */
  fade_in?: Fade | null;
  /**
   * Fade at the end of the clip (V4).
   */
  fade_out?: Fade | null;
  /**
   * 0.0 = transparent, 1.0 = opaque.
   */
  opacity: Animatable;
  /**
   * Playback speed (V4): constant. Media clips only.
   */
  speed?: Speed;
  transform: Transform;
  /**
   * Gain in decibels. 0 = unchanged, -6 = half amplitude.
   */
  volume_db: Animatable;
};

